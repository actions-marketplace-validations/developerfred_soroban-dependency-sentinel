//! Markdown renderer for PR comments.

use crate::DependencyReport;

pub fn render(reports: &[DependencyReport]) -> String {
    let mut out = String::new();
    out.push_str("## 🛡️ Soroban Dependency Sentinel\n\n");

    if reports.is_empty() {
        out.push_str("_No dependencies found._\n");
        return out;
    }

    let cve_count: usize = reports.iter().map(|r| r.vulnerabilities.len()).sum();
    let high_risk = reports
        .iter()
        .filter(|r| {
            matches!(
                r.classification,
                crate::scorer::Classification::High | crate::scorer::Classification::Critical
            )
        })
        .count();

    out.push_str(&format!(
        "**Summary**: {} dependencies · {} advisories · {} high/critical\n\n",
        reports.len(),
        cve_count,
        high_risk
    ));

    out.push_str("| Crate | Version | Score | Class | Pony | Source | Advisories |\n");
    out.push_str("|-------|---------|-------|-------|------|--------|------------|\n");

    for r in reports {
        let advisories = if r.vulnerabilities.is_empty() {
            "—".into()
        } else {
            r.vulnerabilities
                .iter()
                .map(|v| format!("`{}`", v.id))
                .collect::<Vec<_>>()
                .join(", ")
        };
        out.push_str(&format!(
            "| `{}` | `{}` | {:.2} | {:?} | {} | {:?} | {} |\n",
            r.crate_name,
            r.version,
            r.risk_score,
            r.classification,
            r.pony_factor
                .map(|p| p.to_string())
                .unwrap_or_else(|| "—".into()),
            r.pony_source,
            advisories
        ));
    }

    out.push_str("\n_Generated by [soroban-dependency-sentinel](https://github.com/scf-public-goods/soroban-dependency-sentinel)._\n");
    out
}
